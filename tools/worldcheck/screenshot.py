"""In-game screenshots of a generated world: runs the dev client under Xvfb and teleports around.

    python3 tools/worldcheck/screenshot.py run/m1 --out run/shots \\
        --shot "peak:300 260 5000 135 15" --shot "valley:0 120 4800 -90 5"

Each shot is NAME:X Y Z YAW PITCH (Minecraft yaw: 0 = south, 90 = west, 180 = north, -90 = east).
The world is copied to run/saves/<world>-shots with commands enabled and spectator mode, the client
starts with --quickPlaySingleplayer, waits until the player joined, switches to spectator,
hides the HUD (F1), for each shot teleports, waits --settle seconds for chunks to load and
render, and saves a screenshot (F2) as <out>/<name>.png. Time, weather and game rules are set in
level.dat before loading; commands are typed slowly because software rendering makes input lag.

Needs Xvfb, Mesa (software OpenGL) and python-xlib (pip install python-xlib) for XTEST input.
Chunks outside the generated square are generated by the integrated server while waiting, so keep
shots well inside the square generated by generate.py (render distance --render-distance chunks).
"""
import argparse
import glob
import os
import shutil
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nbt  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RUN = os.path.join(ROOT, "run")
DISPLAY = ":99"
WIDTH, HEIGHT = 1600, 900

OPTIONS = {
    "renderDistance": None,
    "simulationDistance": "5",
    "fov": "0.25",
    "guiScale": "2",
    "pauseOnLostFocus": "false",
    "onboardAccessibility": "false",
    "tutorialStep": "none",
    "skipMultiplayerWarning": "true",
    "joinedFirstServer": "true",
    "narrator": "0",
    "soundCategory_master": "0.0",
    "maxFps": "30",
    "graphicsMode": "1",
    "biomeBlendRadius": "2",
    "entityShadows": "false",
    "fullscreen": "false",
    # The cloud layer (Y 192) cuts through mountains and hides shots taken near it.
    "renderClouds": '"false"',
}

KEY_NAMES = {" ": "space", "/": "slash", "-": "minus", ".": "period", "@": "at", "~": "asciitilde",
             "_": "underscore", ":": "colon", "=": "equal"}


def write_options(render_distance):
    path = os.path.join(RUN, "options.txt")
    lines = {}
    if os.path.exists(path):
        with open(path) as f:
            for line in f:
                if ":" in line:
                    key, value = line.rstrip("\n").split(":", 1)
                    lines[key] = value
    for key, value in OPTIONS.items():
        lines[key] = str(render_distance) if key == "renderDistance" else value
    with open(path, "w") as f:
        f.write("".join("%s:%s\n" % kv for kv in lines.items()))


def prepare_world(source, name):
    target = os.path.join(RUN, "saves", name)
    if os.path.exists(target):
        shutil.rmtree(target)
    shutil.copytree(source, target, ignore=shutil.ignore_patterns("session.lock", "worldcheck.json"))
    level = nbt.load(os.path.join(target, "level.dat"))
    data = level["Data"]
    data["allowCommands"] = nbt.Tag(nbt.BYTE, 1)
    data["GameType"] = nbt.Tag(nbt.INT, 3)
    # NeoForge's "experimental settings" confirmation, otherwise shown before loading.
    data["confirmedExperimentalSettings"] = nbt.Tag(nbt.BYTE, 1)
    data.value.pop("Player", None)
    # Noon, clear weather, frozen time: fewer commands to type into a laggy client.
    data["DayTime"] = nbt.Tag(nbt.LONG, 6000)
    data["raining"] = nbt.Tag(nbt.BYTE, 0)
    data["thundering"] = nbt.Tag(nbt.BYTE, 0)
    data["clearWeatherTime"] = nbt.Tag(nbt.INT, 1000000)
    if "GameRules" in data.value:
        rules = data["GameRules"]
        rules["doDaylightCycle"] = nbt.Tag(nbt.STRING, "false")
        rules["doWeatherCycle"] = nbt.Tag(nbt.STRING, "false")
        # generate.py raised the spawn chunk radius; loading all of them would only delay the client.
        rules["spawnChunkRadius"] = nbt.Tag(nbt.STRING, "2")
    nbt.save(os.path.join(target, "level.dat"), level)


class Keyboard:
    def __init__(self):
        from Xlib import X, XK, display
        from Xlib.ext import xtest
        self.X, self.XK, self.xtest = X, XK, xtest
        self.display = display.Display(DISPLAY)

    def focus_game(self):
        root = self.display.screen().root
        for window in root.query_tree().children:
            name = window.get_wm_name() or ""
            if "Minecraft" in name:
                window.set_input_focus(self.X.RevertToParent, self.X.CurrentTime)
                self.xtest.fake_input(self.display, self.X.MotionNotify, x=WIDTH // 2, y=HEIGHT // 2)
                self.display.sync()
                return True
        return False

    def key(self, keysym_name, shift=False):
        # Software rendering runs at a few frames per second and the game reads input once per
        # frame: hold keys long enough to be seen and leave time between them.
        keycode = self.display.keysym_to_keycode(self.XK.string_to_keysym(keysym_name))
        shift_code = self.display.keysym_to_keycode(self.XK.XK_Shift_L)
        if shift:
            self.xtest.fake_input(self.display, self.X.KeyPress, shift_code)
            self.display.sync()
        self.xtest.fake_input(self.display, self.X.KeyPress, keycode)
        self.display.sync()
        time.sleep(0.15)
        self.xtest.fake_input(self.display, self.X.KeyRelease, keycode)
        if shift:
            self.xtest.fake_input(self.display, self.X.KeyRelease, shift_code)
        self.display.sync()
        time.sleep(0.25)

    def type(self, text):
        for ch in text:
            name = KEY_NAMES.get(ch, ch)
            keysym = self.XK.string_to_keysym(name)
            keycode = self.display.keysym_to_keycode(keysym)
            shift = ch.isupper() or self.display.keycode_to_keysym(keycode, 0) != keysym
            self.key(name if not ch.isupper() else ch.lower(), shift)

    def command(self, text):
        # "/" opens the chat with the slash already typed; wait until the chat screen is open.
        self.key("slash")
        time.sleep(5)
        self.type(text[1:] if text.startswith("/") else text)
        time.sleep(2)
        self.key("Return")
        time.sleep(5)


def wait_for(path, needle, proc, timeout):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if proc.poll() is not None:
            raise RuntimeError("client exited early; see " + path)
        with open(path, errors="replace") as f:
            if needle in f.read():
                return
        time.sleep(2)
    raise TimeoutError("'%s' not seen in %s" % (needle, path))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("world")
    p.add_argument("--out", required=True)
    p.add_argument("--shot", action="append", required=True, help="NAME:X Y Z YAW PITCH")
    p.add_argument("--render-distance", type=int, default=12)
    p.add_argument("--settle", type=int, default=90, help="seconds to wait after each teleport")
    args = p.parse_args()

    shots = []
    for spec in args.shot:
        name, coords = spec.split(":", 1)
        x, y, z, yaw, pitch = coords.split()
        shots.append((name, x, y, z, yaw, pitch))
    name = os.path.basename(os.path.normpath(args.world)) + "-shots"
    prepare_world(args.world, name)
    write_options(args.render_distance)
    os.makedirs(args.out, exist_ok=True)

    xvfb = subprocess.Popen(["Xvfb", DISPLAY, "-screen", "0", "%dx%dx24" % (WIDTH, HEIGHT), "-nolisten", "tcp"])
    env = dict(os.environ, DISPLAY=DISPLAY, LIBGL_ALWAYS_SOFTWARE="1")
    log_path = os.path.join(RUN, "screenshot-client.log")
    log = open(log_path, "w")
    client = subprocess.Popen(
        ["./gradlew", "runClient", "--console=plain",
         "-PclientArgs=--quickPlaySingleplayer %s --width %d --height %d" % (name, WIDTH, HEIGHT)],
        cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, env=env)
    try:
        wait_for(log_path, "joined the game", client, 1800)
        time.sleep(15)
        keyboard = Keyboard()
        if not keyboard.focus_game():
            raise RuntimeError("Minecraft window not found on " + DISPLAY)
        keyboard.command("/gamemode spectator")
        keyboard.key("F1")
        screenshots = os.path.join(RUN, "screenshots")
        for shot_name, x, y, z, yaw, pitch in shots:
            keyboard.command("/tp @s %s %s %s %s %s" % (x, y, z, yaw, pitch))
            time.sleep(args.settle)
            before = set(glob.glob(os.path.join(screenshots, "*.png")))
            keyboard.key("F2")
            deadline = time.time() + 30
            new = []
            while time.time() < deadline and not new:
                time.sleep(1)
                new = sorted(set(glob.glob(os.path.join(screenshots, "*.png"))) - before)
            if not new:
                print("no screenshot for", shot_name)
                continue
            # The game writes the PNG on a worker thread: wait until its size stops changing.
            size = -1
            while size != os.path.getsize(new[-1]):
                size = os.path.getsize(new[-1])
                time.sleep(2)
            target = os.path.join(args.out, shot_name + ".png")
            shutil.copyfile(new[-1], target)
            print("wrote", target)
    finally:
        client.terminate()
        try:
            client.wait(timeout=60)
        except subprocess.TimeoutExpired:
            client.kill()
        subprocess.run(["pkill", "-f", "--", "quickPlaySingleplayer " + name], check=False)
        xvfb.terminate()
        log.close()


if __name__ == "__main__":
    main()
